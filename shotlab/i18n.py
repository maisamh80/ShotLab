PERSIAN_LOCALIZED_OPTION_KEYS = frozenset(
    {
        "location_type",
        "time_of_day",
    }
)


def text(language: str, key: str, **values: object) -> str:
    value = STRINGS.get(language, STRINGS["en"]).get(key, key)
    return value.format(**values)


def option_label(language: str, key: str, value: object) -> str:
    for option_value, fa_label, en_label in OPTIONS.get(key, []):
        if option_value == value:
            if (
                language == "fa"
                and key in PERSIAN_LOCALIZED_OPTION_KEYS
            ):
                return fa_label
            return en_label
    return str(value or "")
